// Generate src/api/schema.d.ts from the API's OpenAPI schema, so the dashboard's types follow
// the backend. Usage: npm run gen:types [-- <url or file>]
// Default source: $OPENAPI_URL, else $VITE_API_BASE_URL/openapi.json, else localhost:8001.
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const base = process.env.VITE_API_BASE_URL ?? "http://localhost:8001";
const source = process.argv[2] ?? process.env.OPENAPI_URL ?? `${base.replace(/\/$/, "")}/openapi.json`;
const out = fileURLToPath(new URL("../src/api/schema.d.ts", import.meta.url));

const input = /^https?:/.test(source) ? new URL(source) : new URL(source, `file://${process.cwd()}/`);
let ast;
try {
  ast = await openapiTS(input);
} catch (err) {
  console.error(`could not read the OpenAPI schema from ${source}: ${err.message}`);
  console.error("Is the API running? Start it with .\\scripts\\up.ps1 -Services api");
  process.exit(1);
}
const header =
  "// Generated by scripts/gen-types.mjs from the API's OpenAPI schema. Do not edit by hand:\n" +
  "// run `npm run gen:types` after changing the API.\n\n";
await writeFile(out, header + astToString(ast));
console.log(`wrote ${out} from ${source}`);
